import type { NextConfig } from "next";

// The mode/configuration guard (AT-35) runs in src/instrumentation.ts at
// server startup, where workspace TypeScript packages are compiled by Next.

const config: NextConfig = {
  transpilePackages: ["@px/domain", "@px/demo", "@px/integrations", "@px/db"],
  serverExternalPackages: ["pg"],
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "X-Frame-Options", value: "DENY" },
          // Scripts stay 'self' + inline (Next.js bootstrap). Framing, plugins
          // and base-URL tricks are refused. No form-action: a deposit form
          // redirects to the payment provider's checkout (another origin).
          {
            key: "Content-Security-Policy",
            value: [
              "default-src 'self'",
              `script-src 'self' 'unsafe-inline'${process.env.NODE_ENV === "development" ? " 'unsafe-eval'" : ""}`,
              "style-src 'self' 'unsafe-inline'",
              "img-src 'self' data:",
              "font-src 'self' data:",
              "connect-src 'self'",
              "frame-ancestors 'none'",
              "object-src 'none'",
              "base-uri 'self'",
            ].join("; "),
          },
          { key: "Strict-Transport-Security", value: "max-age=31536000; includeSubDomains" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
        ],
      },
    ];
  },
};

export default config;
